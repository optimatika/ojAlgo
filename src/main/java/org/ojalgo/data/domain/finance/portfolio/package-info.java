/**
 * Classes in this package relate to modelling of financial investment portfolios, and Modern Portfolio
 * Theory.
 * <ul>
 * <li>An asset is a resource with economic value, and something that can be owned.
 * <li>A portfolio is a collection of something (anything).
 * <li>An instrument is a tool or device - an enabler.
 * <li>Financial instruments enable financial transactions, and are defined in terms of assets. A financial
 * instrument can for instance be evidence of ownership of, or a contractual right/obligation to receive or
 * deliver, an asset.
 * <li>Financial portfolios contain financial instruments. Typically, in terms of investments, it is a
 * collection of assets with a common owner.
 * <li>The distinction between assets, instruments and portfolios is fuzzy, and the terms can often be used
 * interchangeably. Here the term portfolio represents the collection and ownership, and the term asset
 * represents components/contents and underlying value. We try to avoid using the term instrument.
 * <li>Return is the relative change in value over a period of time: (V<sub>1</sub> - V<sub>0</sub>) /
 * V<sub>0</sub>. Excess return is the return in excess of the risk-free return.
 * <li>Growth factor is V<sub>1</sub> / V<sub>0</sub> = 1 + return.
 * <li>Growth rate is ln(growth factor) - the continuously compounded, or logarithmic, return.
 * <li>Volatility is the standard deviation of the return.
 * </ul>
 */
